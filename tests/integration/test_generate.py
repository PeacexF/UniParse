@pytest.fixture
def captured(monkeypatch):
    """Answer any chat completion, and hand back what we were asked to send."""
    from uparse.assist import providers

    sent: dict[str, object] = {}

    def post(url, *, json=None, headers=None, timeout=None):
        sent.update(url=url, payload=json, headers=headers)
        return httpx.Response(
            200,
            json={"choices": [{"message": {"content": '{"fields": []}'}}]},
            request=httpx.Request("POST", url),
        )

    monkeypatch.setattr(providers.httpx, "post", post)
    return sent


def _openai(**assist):
    from uparse.assist import providers

    return providers.OpenAICompatibleProvider(
        AssistConfig(provider="openai_compatible", base_url="https://x.test/v1/", **assist)
    )


@pytest.mark.parametrize(
    ("tier", "want"),
    [("schema", "json_schema"), ("json", "json_object"), ("text", None)],
)
def test_the_answer_is_asked_for_as_precisely_as_the_provider_allows(captured, tier, want):
    _openai(tier=tier).complete("s", "u", {"type": "object"})
    fmt = captured["payload"].get("response_format")
    assert (fmt or {}).get("type") == want
    assert captured["url"] == "https://x.test/v1/chat/completions"


def test_the_key_comes_from_the_environment(captured, monkeypatch):
    monkeypatch.setenv("SOME_PROVIDER_KEY", "sk-secret")
    _openai(api_key_env="SOME_PROVIDER_KEY").complete("s", "u", {})
    assert captured["headers"]["Authorization"] == "Bearer sk-secret"


def test_no_key_env_means_no_authorization_header(captured):
    _openai().complete("s", "u", {})
    assert "Authorization" not in captured["headers"]


def test_content_returned_in_parts_is_joined(monkeypatch):
    from uparse.assist import providers

    monkeypatch.setattr(
        providers.httpx,
        "post",
        lambda url, **kw: httpx.Response(
            200,
            json={"choices": [{"message": {"content": [{"text": "{"}, {"text": '"a": 1}'}]}}]},
            request=httpx.Request("POST", url),
        ),
    )
    assert _openai().complete("s", "u", {}) == '{"a": 1}'


def test_a_failing_provider_names_itself(monkeypatch):
    from uparse.assist import providers

    monkeypatch.setattr(
        providers.httpx,
        "post",
        lambda url, **kw: httpx.Response(
            503, text="upstream down", request=httpx.Request("POST", url)
        ),
    )
    with pytest.raises(AssistError, match=r"openai_compatible:.*503"):
        _openai().complete("s", "u", {})


# --- the cache ------------------------------------------------------------


COUNTING = """
import json, os, sys
sys.stdin.read()
tally = os.environ["TALLY"]
n = (int(open(tally).read()) if os.path.exists(tally) else 0) + 1
open(tally, "w").write(str(n))
print(json.dumps({"fields": [{"name": "published", "column": "c2"}]}))
"""


def test_asking_twice_about_the_same_page_calls_the_model_once(tmp_path, site_url, monkeypatch):
    """A free tier is 100-1,000 requests a day. Re-running `generate` on a page already
    analysed must not spend one of them."""
    generate_mod = sys.modules["uparse.assist.generate"]

    script = tmp_path / "counting.py"
    script.write_text(textwrap.dedent(COUNTING))
    tally = tmp_path / "calls"
    monkeypatch.setenv("TALLY", str(tally))
    monkeypatch.setattr(generate_mod, "CACHE_DIR", tmp_path / "cache")

    page = _page(site_url)
    config = _config([sys.executable, str(script)], cache=True)
    first = run_generate(page, config, want="published")
    second = run_generate(page, config, want="published")

    assert first.assisted and second.assisted
    assert not first.cached and second.cached
    assert tally.read_text() == "1"
    assert first.jsonc == second.jsonc


def test_a_read_only_cache_directory_does_not_fail_the_run(tmp_path, site_url, monkeypatch):
    generate_mod = sys.modules["uparse.assist.generate"]

    script = tmp_path / "counting.py"
    script.write_text(textwrap.dedent(COUNTING))
    monkeypatch.setenv("TALLY", str(tmp_path / "calls"))
    blocked = tmp_path / "blocked"
    blocked.write_text("not a directory")
    monkeypatch.setattr(generate_mod, "CACHE_DIR", blocked / "cache")

    result = run_generate(
        _page(site_url), _config([sys.executable, str(script)], cache=True), want="published"
    )
    assert result.assisted and not result.cached
