def test_the_command_provider_never_runs_in_the_user_s_directory(tmp_path, site_url):
    """opencode and friends read whatever project they start in — slow, and the wrong
    blast radius for a prompt built from an untrusted page."""
    script = tmp_path / "pwd.py"
    script.write_text(
        'import json,os,sys; sys.stdin.read(); print(json.dumps({"cwd": os.getcwd()}))'
    )
    provider = CommandProvider(
        AssistConfig(provider="command", command=[sys.executable, str(script)])
    )
    where = json.loads(provider.complete("s", "u", {}))["cwd"]
    assert Path(where).resolve() != Path.cwd().resolve()


def test_a_rate_limited_provider_backs_off_then_says_who_limited_it(monkeypatch):
    from uparse.assist import providers

    monkeypatch.setattr(providers, "MAX_BACKOFF_S", 0.0)
    calls = []

    def limited(url, **kwargs):
        calls.append(url)
        return httpx.Response(
            429, headers={"retry-after": "120"}, request=httpx.Request("POST", url)
        )

    monkeypatch.setattr(providers.httpx, "post", limited)
    provider = providers.OpenAICompatibleProvider(
        AssistConfig(provider="openai_compatible", base_url="https://x.test/v1")
    )
    with pytest.raises(AssistError, match="rate limited"):
        provider.complete("s", "u", {})
    assert len(calls) == providers.RATE_LIMIT_ATTEMPTS


