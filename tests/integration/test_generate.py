# A tool that starts a server and talks to it — the shape opencode and friends have.
ORPHANING = """
import subprocess, sys, time
subprocess.Popen([sys.executable, "-c", "import time; time.sleep(120)  # UPARSE_ORPHAN_MARK"])
time.sleep(120)
"""


def test_a_timed_out_tool_does_not_leave_its_server_running(tmp_path):
    script = tmp_path / "orphaning.py"
    script.write_text(textwrap.dedent(ORPHANING))
    provider = CommandProvider(
        AssistConfig(provider="command", command=[sys.executable, str(script)], timeout_s=2)
    )
    started = time.monotonic()
    try:
        with pytest.raises(AssistError, match="no answer within"):
            provider.complete("s", "u", {})
        assert time.monotonic() - started < 20
        found = subprocess.run(
            ["pgrep", "-f", "UPARSE_ORPHAN_MARK"], capture_output=True, text=True
        )
        assert not found.stdout.split(), "the tool's own child outlived the timeout"
    finally:
        subprocess.run(["pkill", "-f", "UPARSE_ORPHAN_MARK"], capture_output=True)


